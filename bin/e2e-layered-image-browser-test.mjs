import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
const requirePlugin = createRequire(process.cwd() + '/index.js');
const { chromium } = requirePlugin('playwright');
const base = process.env.OPF_BASE_URL || 'http://127.0.0.1:8091';
const passwordFile = process.env.OPF_E2E_PASSWORD_FILE;
const productId = Number(process.env.OPF_LAYERED_PRODUCT_ID);
const productUrl = process.env.OPF_LAYERED_PRODUCT_URL;
const groupId = Number(process.env.OPF_LAYERED_GROUP_ID);
const targetImage = process.env.OPF_LAYERED_TARGET_IMAGE;
const baseImage = process.env.OPF_LAYERED_BASE_IMAGE;
const redImage = process.env.OPF_LAYERED_RED_IMAGE;
const blueImage = process.env.OPF_LAYERED_BLUE_IMAGE;
const goldImage = process.env.OPF_LAYERED_GOLD_IMAGE;
const mismatchImage = process.env.OPF_LAYERED_MISMATCH_IMAGE;
const opaqueImage = process.env.OPF_LAYERED_OPAQUE_IMAGE;
const opaqueAlphaImage = process.env.OPF_LAYERED_OPAQUE_ALPHA_IMAGE;
const uploadFile = process.env.OPF_LAYERED_UPLOAD_FILE;
const opaqueAlphaFile = process.env.OPF_LAYERED_OPAQUE_ALPHA_FILE;
if (!passwordFile || !productId || !productUrl || !groupId || !targetImage || !baseImage || !redImage || !blueImage || !goldImage || !mismatchImage || !opaqueImage || !opaqueAlphaImage || !uploadFile || !opaqueAlphaFile) throw new Error('Layered-image E2E environment is incomplete');

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
await page.addInitScript(() => {
	window.__opfScrollCalls = 0;
	Element.prototype.scrollIntoView = function () { window.__opfScrollCalls++; };
});
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
let failures = 0;
const check = (name, ok) => {
	console.log(`${ok ? 'ok' : 'FAIL'} ${name}`);
	if (!ok) failures++;
};

try {
	await page.goto(`${base}/wp-login.php`, { waitUntil: 'domcontentloaded' });
	await page.locator('#user_login').fill(process.env.OPF_E2E_USER || 'admin');
	await page.locator('#user_pass').fill(readFileSync(passwordFile, 'utf8').trim());
	await page.locator('#wp-submit').click();
	await page.waitForURL('**/wp-admin/**');
	await page.goto(`${base}/wp-admin/post.php?post=${productId}&action=edit`, { waitUntil: 'domcontentloaded' });
	await page.locator('#woocommerce-product-data').waitFor();
	await page.locator('#woocommerce-product-data .product_data_tabs a[href="#opf_layered_images_product_data"]').click();
	const enable = page.locator('#_opf_layered_enabled');
	check('Product Data exposes enabled base, target, delay, auto-scroll, and choice-layer controls', await enable.count() === 1 && await page.locator('#_opf_layered_base').count() === 1 && await page.locator('#_opf_layered_target').count() === 1 && await page.locator('#_opf_layered_delay').count() === 1 && await page.locator('#_opf_layered_scroll').count() === 1);
	await enable.check();
	await page.locator('#_opf_layered_base').selectOption(baseImage);
	await page.locator('#_opf_layered_target').selectOption('gallery');
	await page.locator('#_opf_layered_target_image').selectOption(targetImage);
	await page.locator('#_opf_layered_delay').check();
	await page.locator('#_opf_layered_scroll').check();
	await page.locator('[data-opf-layered-upload="_opf_layered_base"]').click();
	const baseMediaFrame = page.locator('.media-modal:visible').last();
	await baseMediaFrame.waitFor({ state: 'visible' });
	await baseMediaFrame.getByRole('tab', { name: 'Media Library' }).click();
	const opaqueBaseAttachment = baseMediaFrame.locator(`.attachment[data-id="${opaqueAlphaImage}"]`);
	await opaqueBaseAttachment.waitFor({ state: 'visible' });
	await opaqueBaseAttachment.click();
	await baseMediaFrame.locator('.media-button-select').click();
	await baseMediaFrame.waitFor({ state: 'hidden' });
	check('base image media control accepts a same-size opaque PNG', await page.locator('#_opf_layered_base').inputValue() === opaqueAlphaImage && await page.locator('#_opf_layered_base').locator(`option[value="${opaqueAlphaImage}"]`).getAttribute('data-width') === '8');
	const uploadedBaseUrl = await page.locator('#_opf_layered_base').locator(`option[value="${opaqueAlphaImage}"]`).getAttribute('data-url');
	const redLayer = page.locator(`[name="_opf_layered_images[layers][${groupId}:color:red]"]`);
	const blueLayer = page.locator(`[name="_opf_layered_images[layers][${groupId}:color:blue]"]`);
	const goldLayer = page.locator(`[name="_opf_layered_images[layers][${groupId}:trim:gold]"]`);
	check('admin selector rejects wrong-size and opaque PNG sources while allowing equal-size alpha PNGs', await redLayer.locator(`option[value="${redImage}"]`).isEnabled() && await redLayer.locator(`option[value="${mismatchImage}"]`).isDisabled() && await redLayer.locator(`option[value="${opaqueImage}"]`).isDisabled());
	await redLayer.selectOption(opaqueAlphaImage);
	await page.waitForFunction((group) => {
		const select = document.querySelector(`[name="_opf_layered_images[layers][${group}:color:red]"]`);
		return !!select && select.value === '' && (select.parentElement.querySelector('[data-opf-layered-upload-feedback]')?.textContent || '').includes('transparent pixels');
	}, groupId);
	const redLayerFeedback = redLayer.locator('xpath=..').locator('[data-opf-layered-upload-feedback]');
	check('existing-library RGBA image with no transparent pixels is visibly rejected', await redLayer.inputValue() === '' && (await redLayerFeedback.textContent()).includes('transparent pixels'));
	await redLayer.selectOption(redImage);
	await page.waitForFunction((group) => document.querySelector(`[name="_opf_layered_images[layers][${group}:color:red]"]`)?.selectedOptions[0]?.dataset.alpha === '1', groupId);
	await page.waitForFunction((group) => (document.querySelector(`[name="_opf_layered_images[layers][${group}:color:red]"]`)?.parentElement.querySelector('[data-opf-layered-upload-feedback]')?.textContent || '') === '', groupId);
	check('choosing a valid existing layer clears the previous rejection message', (await redLayerFeedback.textContent()) === '');
	await page.locator(`[data-opf-layered-upload="_opf_layer_${groupId}:color:red"]`).click();
	const mediaFrame = page.locator('.media-modal:visible').last();
	await mediaFrame.waitFor({ state: 'visible' });
	check('base/layer image upload button opens the WordPress media library', await mediaFrame.isVisible());
	await mediaFrame.getByRole('tab', { name: 'Upload files' }).click();
	const existingMediaIds = await mediaFrame.locator('.attachment[data-id]').evaluateAll((nodes) => nodes.map((node) => node.dataset.id));
	await mediaFrame.locator('input[type="file"]').last().setInputFiles(uploadFile);
	await page.waitForFunction((existingIds) => {
		const selected = document.querySelector('.media-modal .attachment.selected[data-id]');
		return !!selected && !existingIds.includes(selected.dataset.id);
	}, existingMediaIds);
	const beforeUploadSelection = await redLayer.inputValue();
	await mediaFrame.locator('.media-button-select').click();
	await mediaFrame.waitFor({ state: 'hidden' });
	check('uploaded transparent PNG becomes the selected choice layer', (await redLayer.inputValue()) !== beforeUploadSelection && (await redLayer.inputValue()) !== '');
	const uploadedRedLayer = await redLayer.inputValue();
	const uploadedRedUrl = await redLayer.locator(`option[value="${uploadedRedLayer}"]`).getAttribute('data-url');
	await page.locator(`[data-opf-layered-upload="_opf_layer_${groupId}:color:red"]`).click();
	await mediaFrame.waitFor({ state: 'visible' });
	await mediaFrame.getByRole('tab', { name: 'Upload files' }).click();
	const mediaIdsBeforeOpaqueUpload = await mediaFrame.locator('.attachment[data-id]').evaluateAll((nodes) => nodes.map((node) => node.dataset.id));
	await mediaFrame.locator('input[type="file"]').last().setInputFiles(opaqueAlphaFile);
	await page.waitForFunction((existingIds) => {
		const selected = document.querySelector('.media-modal .attachment.selected[data-id]');
		return !!selected && !existingIds.includes(selected.dataset.id);
	}, mediaIdsBeforeOpaqueUpload);
	await mediaFrame.locator('.media-button-select').click();
	await mediaFrame.waitFor({ state: 'hidden' });
	const alphaRejection = redLayerFeedback;
	check('uploaded RGBA PNG with no transparent pixels is visibly rejected', await redLayer.inputValue() === '' && (await alphaRejection.textContent()).includes('transparent pixels'));
	await redLayer.selectOption(uploadedRedLayer);
	await page.waitForFunction((id) => {
		const select = Array.from(document.querySelectorAll('.opf-layered-choice-image')).find((element) => element.value === id);
		return !!select && select.value === id && select.selectedOptions[0]?.dataset.alpha === '1';
	}, uploadedRedLayer);
	await blueLayer.selectOption(blueImage);
	await goldLayer.selectOption(goldImage);
	await page.locator('#publish').click();
	await page.waitForLoadState('domcontentloaded');
	await page.locator('#woocommerce-product-data .product_data_tabs a[href="#opf_layered_images_product_data"]').click();
	check('uploaded base image, gallery identity, and per-choice layer mappings persist across product save/reload', await page.locator('#_opf_layered_enabled').isChecked() && await page.locator('#_opf_layered_base').inputValue() === opaqueAlphaImage && await page.locator('#_opf_layered_target').inputValue() === 'gallery' && await page.locator('#_opf_layered_target_image').inputValue() === targetImage && await page.locator('#_opf_layered_delay').isChecked() && await page.locator('#_opf_layered_scroll').isChecked() && await page.locator(`[name="_opf_layered_images[layers][${groupId}:color:red]"]`).inputValue() === uploadedRedLayer && await page.locator(`[name="_opf_layered_images[layers][${groupId}:color:blue]"]`).inputValue() === blueImage && await page.locator(`[name="_opf_layered_images[layers][${groupId}:trim:gold]"]`).inputValue() === goldImage);

	await page.goto(productUrl, { waitUntil: 'domcontentloaded' });
	await page.waitForFunction(() => Array.isArray(window.OPF_LAYERED_IMAGES) && window.OPF_LAYERED_IMAGES.length === 1 && window.OPF_LAYERED_IMAGES[0].layers.length === 3);
	const runtime = await page.evaluate(() => window.OPF_LAYERED_IMAGES[0]);
	check('runtime selects the requested second Woo gallery image and exposes the uploaded opaque 8×4 base plus valid layer', runtime.target === 'gallery' && runtime.target_index === 1 && runtime.base_width === 8 && runtime.base_height === 4 && runtime.base_url === uploadedBaseUrl && runtime.layers.length === 3 && runtime.layers[0].url === uploadedRedUrl);
	const targetSlide = page.locator('.woocommerce-product-gallery__image').nth(1);
	const stack = targetSlide.locator('[data-opf-layered-image="0"]');
	check('delay keeps the original selected gallery image before any mapped choice', await stack.isHidden() && await targetSlide.locator('img').first().evaluate((node) => getComputedStyle(node).opacity === '1'));
	const redChoice = page.locator(`[data-opf-field="color"] input[value="red"]`);
	const blueChoice = page.locator(`[data-opf-field="color"] input[value="blue"]`);
	const goldChoice = page.locator(`[data-opf-field="trim"] input[value="gold"]`);
	await page.evaluate(() => { window.__opfScrollCalls = 0; });
	await redChoice.check();
	check('first mapped choice shows the base and matching transparent PNG layer and triggers one auto-scroll', await stack.isVisible() && await stack.locator('.opf-layered-image-stack__base').getAttribute('src') === runtime.base_url && await stack.locator('.opf-layered-image-stack__layer').nth(0).isVisible() && await stack.locator('.opf-layered-image-stack__layer').nth(0).evaluate((node) => node.naturalWidth === 8 && node.naturalHeight === 4 && getComputedStyle(node).objectFit === 'fill') && await page.evaluate(() => window.__opfScrollCalls) === 1);
	await goldChoice.check();
	check('independent option choices compose simultaneously', await stack.locator('.opf-layered-image-stack__layer').nth(0).isVisible() && await stack.locator('.opf-layered-image-stack__layer').nth(2).isVisible());
	await redChoice.uncheck();
	await blueChoice.check();
	check('changing a choice swaps its image while retaining the independent layer', await stack.locator('.opf-layered-image-stack__layer').nth(0).isHidden() && await stack.locator('.opf-layered-image-stack__layer').nth(1).isVisible() && await stack.locator('.opf-layered-image-stack__layer').nth(2).isVisible());
	await blueChoice.uncheck();
	await goldChoice.uncheck();
	check('clearing the final selection restores the original gallery image when delay is enabled', await stack.isHidden() && await targetSlide.locator('img').first().evaluate((node) => getComputedStyle(node).opacity === '1'));
	await redChoice.check();
	check('auto-scroll runs only once while choices change and are cleared', await page.evaluate(() => window.__opfScrollCalls) === 1);
	await redChoice.uncheck();
	await page.goto(`${base}/wp-admin/post.php?post=${productId}&action=edit`, { waitUntil: 'domcontentloaded' });
	await page.locator('#woocommerce-product-data .product_data_tabs a[href="#opf_layered_images_product_data"]').click();
	await page.locator('#_opf_layered_delay').uncheck();
	await page.locator('#publish').click();
	await page.waitForLoadState('domcontentloaded');
	await page.goto(productUrl, { waitUntil: 'domcontentloaded' });
	await page.waitForFunction(() => Array.isArray(window.OPF_LAYERED_IMAGES) && window.OPF_LAYERED_IMAGES.length === 1);
	const immediateStack = page.locator('.woocommerce-product-gallery__image').nth(1).locator('[data-opf-layered-image="0"]');
	await page.waitForFunction(() => {
		const baseImage = document.querySelector('.woocommerce-product-gallery__image [data-opf-layered-image="0"] .opf-layered-image-stack__base');
		return !!baseImage && baseImage.complete && baseImage.naturalWidth === 8 && baseImage.naturalHeight === 4;
	});
	check('without delay the base image is shown before any option is selected', await immediateStack.isVisible() && await immediateStack.locator('.opf-layered-image-stack__base').evaluate((node) => node.naturalWidth === 8 && node.naturalHeight === 4));
	await page.locator('[data-opf-field="color"] input[value="blue"]').check();
	await page.locator('[data-opf-field="color"] input[value="blue"]').uncheck();
	const noDelayClear = await immediateStack.evaluate((stack) => {
		const layer = stack.querySelectorAll('.opf-layered-image-stack__layer')[1];
		const base = stack.querySelector('.opf-layered-image-stack__base');
		return { stackVisible: !stack.hidden && 'none' !== getComputedStyle(stack).display, baseLoaded: !!base && base.complete && 8 === base.naturalWidth && 4 === base.naturalHeight, unselectedLayerHidden: !!layer && layer.hidden, selected: Array.from(document.querySelectorAll('[data-opf-field="color"] input:checked')).map((node) => node.value), delay: window.OPF_LAYERED_IMAGES?.[0]?.delay };
	});
	check('without delay clearing options returns to the base background', noDelayClear.stackVisible && noDelayClear.baseLoaded && noDelayClear.unselectedLayerHidden && noDelayClear.selected.length === 0 && noDelayClear.delay === false);
	await page.goto(`${base}/wp-admin/post.php?post=${productId}&action=edit`, { waitUntil: 'domcontentloaded' });
	await page.locator('#woocommerce-product-data .product_data_tabs a[href="#opf_layered_images_product_data"]').click();
	await page.locator('#_opf_layered_delay').check();
	await page.locator('#publish').click();
	await page.waitForLoadState('domcontentloaded');
	check('layer composition browser flow has no uncaught JavaScript errors', errors.length === 0);
	if (errors.length) console.log(errors.join('\n'));
} finally {
	await browser.close();
}
if (failures) process.exit(1);
