import { createRequire } from 'node:module';
const requireFromPlugin = createRequire(process.cwd() + '/index.js');
const { chromium } = requireFromPlugin('playwright');
const base = process.env.OPF_BASE_URL || 'http://127.0.0.1:8091';
const browser = await chromium.launch();
const page = await browser.newPage();
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
await page.goto(`${base}/product/opf-e2e-upload-dimensions-product/`, { waitUntil: 'domcontentloaded' });
const uploader = page.locator('[data-opf-upload]');
const input = uploader.locator('input[type="file"]');
const tinyPng = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR4nGNgYGBgAAAABQABh6FO1AAAAABJRU5ErkJggg==', 'base64');
await input.setInputFiles({ name: 'claimed-large.png', mimeType: 'image/png', buffer: tinyPng });
await page.locator('[data-opf-upload-status]').filter({ hasText: 'at least 2 pixels wide' }).waitFor({ timeout: 10000 });
if (await uploader.locator('[data-opf-upload-token]').count()) throw new Error('Undersized image was staged despite server minimum dimensions.');
if (errors.length) throw new Error(`Browser errors: ${errors.join('; ')}`);
console.log('Real browser upload request rejected 1×1 image against 2×2 minimum using server response.');
console.log('No upload token was issued and no uncaught JavaScript errors occurred.');
await browser.close();
